
//*  Assignment Operators
//? Used to assign values to variables. It includes following operators -


//^    =	:   Assignment	
//^    +=	:   Add and assign	
//^    -=	:   Subtract and assign
//^    *=	:   Multiply and assign	
//^    /=	:   Divide and assign	
//^    %=	:   Modulus and assign	


let x = 5;

console.log( x );
console.log(x+=5);
console.log(x-=3);
console.log(x*=2);
console.log(x/=4);
console.log(x%=2);


//? Note - After each calculation, the value will be assigned to 'x' so it will get new values consecutively.































