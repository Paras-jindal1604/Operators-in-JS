
// * Arithmetic Operators
//? Used for performing mathematical calculations. It includes following operators - 

//^    +   : 	Addition	
//^    -   : 	Subtraction	
//^    *   : 	Multiplication	
//^    /   : 	Division	
//^    %   : 	Modulus (Remainder)	
//^    ++  : 	Increment	
//^    --  : 	Decrement


let a = 5;
let b = 2;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a++);
console.log(++b);
console.log(--a);
console.log(b--);


